import 'dart:io';

import 'os_macos.dart';

/// Граница операционной системы.
///
/// Всё, что в Dart делается по-разному на разных системах — где лежат
/// файлы, как найти чужой процесс, чем переложить звук в WAV, как показать
/// файл в проводнике, — объявлено здесь и реализовано в `os_<система>.dart`.
/// Остальной Dart пользуется только этим договором и про систему не знает
/// ничего.
///
/// Отдельно от `bridge.dart`: там разговор с родным кодом приложения
/// (перехват клавиш, микрофон, окна), и он на всех системах устроен
/// одинаково — один канал, разные реализации на той стороне. Здесь же
/// разница живёт в самом Dart.
///
/// Порт на Windows — это один новый файл `os_windows.dart` и одна строка
/// в [_forCurrentPlatform]. Ничего другого трогать не придётся:
/// `pgrep` там станет `tasklist`, `afconvert` — `ffmpeg`, `open -R` —
/// `explorer /select,`.

const appName = 'tsukiko';

/// Обратный домен приложения: им называется и папка настроек, и запись
/// в автозапуске, и bundle id на macOS.
const bundleId = 'app.yuko.tsukiko';

/// Снимок процесса: столько-то памяти и столько-то потраченного
/// процессорного времени. Само по себе бесполезно — смысл появляется
/// в разнице между двумя снимками.
typedef ProcSample = ({int pid, int rssKb, double cpuSeconds, String name});

/// Процесс со своей командной строкой. По ней узнаётся, чей он: имя
/// процесса у двух копий одной программы одинаковое, аргументы — нет.
typedef ProcListing = ({int pid, int rssKb, String args});

abstract class Os {
  // ── где что лежит ─────────────────────────────────────────────────────────

  /// Домашняя папка пользователя.
  String get home;

  /// Данные приложения: настройки, скачанные модели, pid сервера.
  String get supportDir;

  /// Куда по умолчанию складывать расшифровки. Обычная папка на виду,
  /// а не спрятанная в данных приложения.
  String get defaultLibraryPath;

  /// Папка документов — начальная точка для диалога выбора папки.
  String get documentsDir;

  /// Общие для системы папки, где могут лежать модели whisper, положенные
  /// не нами. Своя папка моделей сюда не входит: её знает [modelsDir].
  List<String> get sharedModelDirs;

  /// Наша папка моделей — та, куда качает загрузчик.
  String get modelsDir => join(supportDir, 'models');

  /// Собрать путь из частей. Разделитель у каждой системы свой, и
  /// склеивать строки через «/» руками — прямой путь к неработающему
  /// Windows.
  String join(String a, [String? b, String? c]) =>
      [a, ?b, ?c].join(Platform.pathSeparator);

  /// Имя файла из полного пути.
  String basename(String path) {
    final at = path.lastIndexOf(Platform.pathSeparator);
    return at < 0 ? path : path.substring(at + 1);
  }

  /// Папка, в которой лежит файл.
  String dirname(String path) {
    final at = path.lastIndexOf(Platform.pathSeparator);
    return at <= 0 ? path : path.substring(0, at);
  }

  // ── чем считать ───────────────────────────────────────────────────────────

  /// Найти программу: сначала в PATH, потом в местах, куда её кладут
  /// пакетные менеджеры этой системы. Возвращает путь или null.
  String? findExecutable(String name);

  /// Что сказать человеку, у которого whisper.cpp не установлен.
  String get whisperInstallHint;

  // ── как система называет свои вещи ────────────────────────────────────────

  /// Имя проводника файлов: «Finder», «Проводник». Встречается в подписях
  /// кнопок, и на чужой системе «Показать в Finder» — прямая неправда.
  String get fileManagerName;

  /// Как эта система рисует модификатор в подписи к сочетанию клавиш.
  /// На macOS это значки (⌘, ⌥), на Windows — слова (Ctrl, Alt).
  String modifierLabel(String mod);

  /// Собрать подпись сочетания из модификаторов и клавиши. Разделитель
  /// тоже разный: macOS ставит значки вплотную, Windows — через плюс.
  String shortcutLabel(List<String> mods, [String? key]);

  // ── звук ──────────────────────────────────────────────────────────────────

  /// Переложить любой звук в 16 кГц моно WAV — ровно то, что whisper ест
  /// без пересчёта. Не осилили — возвращаем исходник как есть, пусть
  /// whisper попробует сам.
  Future<String> toWav(String src, String dst);

  // ── процессы ──────────────────────────────────────────────────────────────

  /// Жив ли процесс. Синхронно: спрашивают это и на выходе из приложения.
  bool isAlive(int pid);

  /// Попросить процесс завершиться ([force] — потребовать).
  void signal(int pid, {bool force = false});

  /// Кто держит эти файлы открытыми. Самая дорогая проверка из всех.
  Future<List<int>> holdersOf(List<String> paths);

  /// Процессы, в чьей командной строке встречается [pattern].
  Future<List<int>> pidsMatching(String pattern);

  /// Процессы с таким именем.
  Future<List<int>> pidsNamed(String name);

  /// Память и процессорное время перечисленных процессов.
  Future<List<ProcSample>> sample(Iterable<int> pids);

  /// Все процессы с их командными строками.
  Future<List<ProcListing>> listProcesses();

  /// Сколько памяти процесс занимает на самом деле, в мегабайтах.
  ///
  /// Именно «на самом деле»: на macOS `rss` занижает всё, что пришло
  /// через mmap, а модель приходит именно так.
  Future<int> footprintMb(int pid);

  // ── система ───────────────────────────────────────────────────────────────

  /// Показать файл в проводнике системы (папку — открыть).
  ///
  /// Возвращает false, если показывать нечего. Ничего при этом не создаёт:
  /// раньше на исчезнувший файл здесь создавалась папка с его именем
  /// и открывалась — человеку показывали «запись», которой нет, а в
  /// библиотеке оставался мусор.
  Future<bool> reveal(String path);

  /// Чьё это приложение, если судить по пути к его данным.
  ///
  /// Программы держат модели у себя в папке данных, и по такому пути
  /// сосед угадывается ещё до того, как мы впервые увидели его процесс.
  /// Где именно лежат данные приложений — у каждой системы своё.
  String? appOwnerOf(String path);

  /// Позвать [onSignal], когда система просит приложение завершиться.
  ///
  /// Отдельным методом, потому что на Windows `ProcessSignal.sigterm.watch()`
  /// не поддерживается вовсе и бросает исключение — то есть портированное
  /// приложение падало бы на старте.
  void onTerminate(void Function() onSignal);
}

/// Реализация для системы, на которой мы работаем.
///
/// Не `final`: тесты подменяют её на свою, чтобы не ходить в настоящую
/// систему. Больше её менять некому.
Os os = _forCurrentPlatform();

Os _forCurrentPlatform() {
  if (Platform.isMacOS) return MacOs();
  // Здесь появится `if (Platform.isWindows) return WindowsOs();`
  throw UnsupportedError(
      'tsukiko пока умеет работать только на macOS: для ${Platform.operatingSystem} '
      'нужна своя реализация Os (см. lib/os.dart).');
}
