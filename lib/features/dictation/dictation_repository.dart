import '../../platform/bridge.dart';

/// Что сейчас с диктовкой — с точки зрения очереди.
///
/// Диктовка и очередь живут в разных изолятах, и напрямую заглянуть
/// в чужой блок нельзя. Спрашиваем через родную сторону: только изолят
/// панели знает, говорит ли человек прямо сейчас.
enum DictationStatus {
  /// Модели в памяти нет — очередь может начинать не спрашивая.
  away,

  /// Модель в памяти, но ничего не происходит: ни записи, ни распознавания.
  /// Её можно выгрузить, если спросить человека.
  resting,

  /// Идёт запись или распознавание фразы. Здесь очередь ждёт: фраза длится
  /// секунды, а прерванная пропадает совсем — переговорить её нельзя.
  busy,
}

/// Дорога от очереди к диктовке.
///
/// Ради этого класса и заведён: очередь не должна знать ни про каналы,
/// ни про изоляты — ей нужно только «занято или нет» и «освободи».
class DictationRepository {
  DictationRepository(this._bridge);
  final NativeBridge _bridge;

  /// Нет родной стороны — нет и диктовки: так это выглядит в тестах
  /// и так же выглядело бы на системе, где панель не поднялась. Молчание
  /// здесь безопаснее исключения: очередь просто начнёт работать.
  Future<DictationStatus> status() async {
    try {
      return switch (await _bridge.dictationStatus()) {
        'busy' => DictationStatus.busy,
        'resting' => DictationStatus.resting,
        _ => DictationStatus.away,
      };
    } catch (_) {
      return DictationStatus.away;
    }
  }

  /// Попросить диктовку отдать память. Возвращается, когда сервер погашен.
  Future<void> release() async {
    try {
      await _bridge.releaseModel();
    } catch (_) {}
  }
}
